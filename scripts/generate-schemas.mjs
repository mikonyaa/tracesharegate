for (const [name, schema] of Object.entries({
  report,
  manifest,
  policy: policyDefinition,
}))
  await writeFile(
    "schemas/" + name + ".schema.json",
    JSON.stringify(
      {
        $schema: "http://json-schema.org/draft-07/schema#",
        title: "TraceShareGate " + name,
        ...schema,
      },
      null,
      2,
    ) + "\n",
  );
